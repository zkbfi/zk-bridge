import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { defineConfig, type Plugin } from "vite";

/** The files whose content the bundle holds. The page's test compares this list's hash with the one in the bundle. */
export const BUNDLE_SOURCES = ["../core/src/search-query.ts", "../data/src/chain-metadata.ts", "../data/src/search.ts", "indexer-search/entry.ts"] as const;

/** The hash of the sources, in the order of {@link BUNDLE_SOURCES}. */
export const sourcesHash = (): string => {
  const hash = createHash("sha256");
  for (const source of BUNDLE_SOURCES) hash.update(source).update("\0").update(readFileSync(fileURLToPath(new URL(source, import.meta.url))));
  return hash.digest("hex");
};

const stamp = (): Plugin => ({
  name: "stamp",
  generateBundle(_options, bundle) {
    for (const file of Object.values(bundle)) if (file.type === "chunk") file.code = `/* Generated by explorer/web/vite.indexer-search.config.ts. Do not edit. sources sha256: ${sourcesHash()} */\n${file.code}`;
  },
});

// One classic script for a page with no build step: `ZkbSearch` on the global object.
export default defineConfig({
  publicDir: false,
  plugins: [stamp()],
  resolve: { alias: { "@zkb/core": fileURLToPath(new URL("../core/src/index.ts", import.meta.url)) } },
  build: {
    outDir: fileURLToPath(new URL("../../deploy/app-server/indexer-home", import.meta.url)),
    emptyOutDir: false,
    minify: true,
    lib: { entry: fileURLToPath(new URL("indexer-search/entry.ts", import.meta.url)), name: "ZkbSearch", formats: ["iife"], fileName: () => "zkb-search.js" },
  },
});
