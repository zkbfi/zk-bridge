// Extracts the ABI of each bridge contract from the Foundry build output (`out/`) into typed TypeScript.
//
// Usage: node scripts/generate-abis.mjs [foundryOutDirectory]
// Run `forge build` in the repository root first. The default directory is `<repository>/out`.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const contractNames = [
  "MessageBridge",
  "TokenMediator",
  "BridgedToken",
  "TokenFactory",
  "DeliveryRouter",
  "BeaconLightClient",
  "BeaconForkGate",
  "ForkRegistry",
  "Multicall3",
];

/**
 * The external libraries linked into a contract. They run with DELEGATECALL in the contract, so their errors and events
 * come from the contract's address; the compiler leaves them out of the contract's ABI. They are appended to it here (each
 * signature once), so a revert or a log of the library decodes with the contract's ABI.
 */
const linkedLibraries = {
  MessageBridge: ["ReceiptProofLib", "OpeningProofLib", "BeaconLayoutLib"],
  TokenMediator: ["MediatorPayloads"],
};

const here = dirname(fileURLToPath(import.meta.url));
const outDirectory = resolve(process.argv[2] ?? join(here, "..", "..", "..", "out"));
const targetDirectory = join(here, "..", "src", "abis");

/** `MessageBridge` becomes `messageBridgeAbi`. */
const exportNameOf = (contractName) => `${contractName[0].toLowerCase()}${contractName.slice(1)}Abi`;

/** `MessageBridge` becomes `message-bridge`. */
const fileNameOf = (contractName) => contractName.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

/** Reads the ABI array of one contract. Fails with a clear message when the build output is missing. */
const readAbi = (contractName) => {
  const path = join(outDirectory, `${contractName}.sol`, `${contractName}.json`);
  let artifact;
  try {
    artifact = JSON.parse(readFileSync(path, "utf8"));
  } catch (error) {
    throw new Error(`cannot read ${path}: run \`forge build\` in the repository root (${error.message})`);
  }
  if (!Array.isArray(artifact.abi)) throw new Error(`${path} has no abi array`);
  return artifact.abi;
};

/** The canonical signature of an ABI entry, to append each error or event of a library once. */
const typeOf = (parameter) =>
  parameter.type.startsWith("tuple")
    ? `(${parameter.components.map(typeOf).join(",")})${parameter.type.slice(5)}`
    : parameter.type;
const signatureOf = (entry) => `${entry.type} ${entry.name ?? ""}(${(entry.inputs ?? []).map(typeOf).join(",")})`;

/** The ABI of a contract with the errors and the events of its linked libraries appended. */
const abiWithLibraries = (contractName) => {
  const abi = readAbi(contractName);
  const known = new Set(abi.map(signatureOf));
  for (const library of linkedLibraries[contractName] ?? []) {
    for (const entry of readAbi(library)) {
      if (entry.type !== "error" && entry.type !== "event") continue;
      const signature = signatureOf(entry);
      if (known.has(signature)) continue;
      known.add(signature);
      abi.push(entry);
    }
  }
  return abi;
};

mkdirSync(targetDirectory, { recursive: true });
const indexLines = ["// Generated by scripts/generate-abis.mjs. Do not edit."];
for (const contractName of contractNames) {
  const abi = abiWithLibraries(contractName);
  const exportName = exportNameOf(contractName);
  const fileName = fileNameOf(contractName);
  const body = [
    "// Generated by scripts/generate-abis.mjs from the Foundry build output. Do not edit.",
    `/** The ABI of \`${contractName}\`. */`,
    `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;`,
    "",
  ].join("\n");
  writeFileSync(join(targetDirectory, `${fileName}.ts`), body);
  indexLines.push(`export { ${exportName} } from "./${fileName}.js";`);
  console.log(`${contractName}: ${abi.length} entries`);
}
writeFileSync(join(targetDirectory, "index.ts"), `${indexLines.join("\n")}\n`);
