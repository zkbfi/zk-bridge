#!/usr/bin/env node
/**
 * Writes `src/bundled-fork-schedules.ts`: the fork schedule and the clock of each chain's beacon chain, as its public beacon
 * node answers them now. Run it at release time (`pnpm --filter @zkb/core run fork-schedules`), so every build carries a
 * schedule that the fork cutover falls back to when no beacon node answers (`bundledForkSchedule` of `fork-cutover.ts`).
 *
 * Why fetched and not taken from the light client's chain table (`light-client/crates/lc-core/src/chain.rs`): the table
 * lists only the forks that the light-client program was built for, and it is fixed with the program keys. The cutover
 * exists for the next fork, which is exactly the one the table does not hold.
 *
 * Each node's genesis validators root is checked against the chain's, so a node of another chain fails the run. The file
 * is written only when every chain answered. No URL holds a key.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/** The public keyless beacon node of each chain (the defaults of the dapp and the terminal), and its genesis validators root. */
const CHAINS = [
  { chainId: 1, url: "https://ethereum-beacon-api.publicnode.com", root: "0x4b363db94e286120d76eb905340fdd4e54bfe9f06bf33ff6cf5ad27f511bfe95" },
  { chainId: 369, url: "https://rpc-pulsechain.g4mm4.io/beacon-api", root: "0x3357ba0018a2582aeabe4ae847aa17d50a3a99aaeb66293c01f80a83aecd0c90" },
  { chainId: 11155111, url: "https://lodestar-sepolia.chainsafe.io", root: "0xd8ea171f3c94aea21ebc42a1ed61052acf3f9209c00e4efbaaddac09ed9b8078" },
  { chainId: 943, url: "https://rpc-testnet-pulsechain.g4mm4.io/beacon-api", root: "0xd81664ba97279a6fa0832041b4aee6009172b4750a99467ff670a9faf3a34e64" },
];

const getJson = async (url, path) => {
  const response = await fetch(`${url}${path}`, { headers: { accept: "application/json" }, signal: AbortSignal.timeout(20_000) });
  if (!response.ok) throw new Error(`chain answered ${response.status} for ${path}`);
  return response.json();
};

const fetchedAt = Math.floor(Date.now() / 1000);
const out = {};
for (const chain of CHAINS) {
  const [schedule, genesis, spec] = await Promise.all([getJson(chain.url, "/eth/v1/config/fork_schedule"), getJson(chain.url, "/eth/v1/beacon/genesis"), getJson(chain.url, "/eth/v1/config/spec")]);
  if (genesis.data.genesis_validators_root.toLowerCase() !== chain.root) throw new Error(`the beacon node of chain ${chain.chainId} follows another beacon chain`);
  out[chain.chainId] = {
    fetchedAt,
    genesisTime: Number(genesis.data.genesis_time),
    secondsPerSlot: Number(spec.data.SECONDS_PER_SLOT),
    slotsPerEpoch: Number(spec.data.SLOTS_PER_EPOCH),
    forkSchedule: schedule.data.map((entry) => ({ current_version: entry.current_version, epoch: entry.epoch })),
  };
}

const target = fileURLToPath(new URL("../src/bundled-fork-schedules.ts", import.meta.url));
writeFileSync(
  target,
  `// Generated by scripts/fetch-fork-schedules.mjs at ${new Date(fetchedAt * 1000).toISOString()}. Do not edit; run it again at release time.\n` +
    `/** The fork schedule and clock of each chain's beacon chain at release time, by chain id, as the beacon node answered them. */\n` +
    `export const BUNDLED_FORK_SCHEDULE_ANSWERS: Readonly<Record<number, { readonly fetchedAt: number; readonly genesisTime: number; readonly secondsPerSlot: number; readonly slotsPerEpoch: number; readonly forkSchedule: readonly { readonly current_version: string; readonly epoch: string }[] }>> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`wrote ${Object.keys(out).length} chains to ${target}`);
